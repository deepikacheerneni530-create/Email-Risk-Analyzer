from email import policy
from email.parser import Parser
from email.utils import parseaddr
import re

# 1. Read sample email
with open("sample_email.txt", "r", encoding="utf-8") as file:
    raw_email = file.read()

# 2. Parse email
email_message = Parser(policy=policy.default).parsestr(raw_email)

# 3. Extract headers
sender = email_message.get("From", "")
return_path = email_message.get("Return-Path", "")
subject = email_message.get("Subject", "")
authentication = email_message.get("Authentication-Results", "")

# 4. Extract body
body_part = email_message.get_body(preferencelist=("plain",))
body = body_part.get_content() if body_part else ""

# 5. Initialize risk score and findings
risk_score = 0
findings = []

# 6. Check urgent words
urgent_words = [
    "urgent", "immediately", "suspended",
    "verify", "blocked", "only 10 minutes"
]

matched_urgent = [
    word for word in urgent_words
    if word in (subject + " " + body).lower()
]

if matched_urgent:
    risk_score += 20
    findings.append(
        "Urgent or threatening language detected: "
        + ", ".join(matched_urgent)
    )

# 7. Check URLs in the email body
urls = re.findall(r"https?://[^\s<>\"']+", body)

if urls:
    findings.append("URL(s) detected: " + ", ".join(urls))

    if any(url.lower().startswith("http://") for url in urls):
        risk_score += 20
        findings.append("Unencrypted HTTP link detected.")

# 8. Check SPF and DKIM
auth_lower = authentication.lower()

if "spf=fail" in auth_lower:
    risk_score += 20
    findings.append("SPF authentication failure detected.")

if "dkim=fail" in auth_lower:
    risk_score += 20
    findings.append("DKIM authentication failure detected.")

# 9. Compare sender and return-path email addresses
sender_email = parseaddr(sender)[1].lower()
return_email = parseaddr(return_path)[1].lower()

if sender_email and return_email:
    sender_domain = sender_email.split("@")[-1]
    return_domain = return_email.split("@")[-1]

    if sender_domain != return_domain:
        risk_score += 20
        findings.append(
            "Sender domain and Return-Path domain do not match."
        )

# 10. Limit score to 100
risk_score = min(risk_score, 100)

# 11. Classify risk
if risk_score >= 80:
    risk_level = "CRITICAL"
elif risk_score >= 60:
    risk_level = "HIGH"
elif risk_score >= 30:
    risk_level = "MEDIUM"
else:
    risk_level = "LOW"

# 12. Display security analysis
print("\n" + "=" * 50)
print("       PHISHING DETECTION REPORT")
print("=" * 50)

print("Sender:", sender)
print("Subject:", subject)
print("\nRisk Score:", risk_score, "/ 100")
print("Risk Level:", risk_level)

print("\n--- SECURITY FINDINGS ---")

if findings:
    for finding in findings:
        print("[WARNING]", finding)
else:
    print("No suspicious indicators detected.")

print("\n--- RECOMMENDATION ---")

if risk_level in ["HIGH", "CRITICAL"]:
    print("Do not click links or provide personal information.")
    print("Verify the sender through an independent trusted channel.")
elif risk_level == "MEDIUM":
    print("Be cautious. Verify the email before taking action.")
else:
    print("No major indicators detected. Still verify unexpected emails.")

print("\nAnalysis completed.")
# 13. Generate Email Security Audit Report

from datetime import datetime
from pathlib import Path

# Create reports folder if it does not exist
report_folder = Path("reports")
report_folder.mkdir(exist_ok=True)

# Get current date and time
analysis_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

# Prepare report content
report_content = f"""
========================================
       EMAIL SECURITY AUDIT REPORT
========================================

Analysis Date and Time: {analysis_time}

EMAIL DETAILS
----------------------------------------
Sender: {sender}
Subject: {subject}

SECURITY ANALYSIS
----------------------------------------
Risk Score: {risk_score}/100
Risk Level: {risk_level}

SECURITY FINDINGS
----------------------------------------
"""

# Add findings to the report
if findings:
    for finding in findings:
        report_content += f"- {finding}\n"
else:
    report_content += "No suspicious indicators detected.\n"

report_content += f"""
RECOMMENDATION
----------------------------------------
"""

if risk_level in ["HIGH", "CRITICAL"]:
    report_content += (
        "Do not click links or provide personal information.\n"
        "Verify the sender through an independent trusted channel.\n"
    )
elif risk_level == "MEDIUM":
    report_content += (
        "Be cautious. Verify the email before taking action.\n"
    )
else:
    report_content += (
        "No major indicators detected. Still verify unexpected emails.\n"
    )

report_content += """
========================================
Report generated by Email Risk Analyzer
========================================
"""

# Save report to file
report_file = report_folder / "email_audit_report.txt"
report_file.write_text(report_content, encoding="utf-8")

print("\nAudit report saved successfully!")
print("Report location:", report_file)